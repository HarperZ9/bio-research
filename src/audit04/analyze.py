"""Merge coder A and B codes, compute kappa and OVERREACH shares.

Writes data/audit04/merged.csv and data/audit04/results.md. Original code
files are read only, never modified.
"""
import csv
from collections import Counter

from config import DATA
from stats import cohen_kappa, fmt_share

CODES = ["ACCURATE", "OVERREACH", "NEUTRAL", "UNCLEAR"]


def read(path):
    with open(path, encoding="utf-8", newline="") as fh:
        return {r["id"]: r for r in csv.DictReader(fh)}


def merge():
    sample, a, b = (read(DATA / f) for f in
                    ("sample.csv", "codes_A.csv", "codes_B.csv"))
    missing = set(sample) - set(a) | set(sample) - set(b)
    if missing:
        raise ValueError(f"ids missing from a code file: {sorted(missing)}")
    rows = []
    for uid, s in sorted(sample.items()):
        ca, cb = a[uid]["code"].strip().upper(), b[uid]["code"].strip().upper()
        for c in (ca, cb):
            if c not in CODES:
                raise ValueError(f"{uid}: bad code {c!r}")
        sub = set()
        if ca == cb == "OVERREACH":
            for r in (a[uid], b[uid]):
                sub |= {t.strip()[:2] for t in r["subtypes"].split(";") if t.strip()}
        rows.append({
            "id": uid, "target": s["target"], "year": s["year"],
            "bucket": s["bucket"], "code_A": ca, "code_B": cb,
            "agree": ca == cb,
            "strict_over": ca == cb == "OVERREACH",
            "lenient_over": "OVERREACH" in (ca, cb),
            "multi_any": "Y" in (a[uid]["multi_cite"].upper(), b[uid]["multi_cite"].upper()),
            "hedged_any": "Y" in (a[uid]["hedged"].upper(), b[uid]["hedged"].upper()),
            "subtypes_agreed": ";".join(sorted(sub)),
        })
    return rows


def substantive(r, who):
    codes = [r["code_A"], r["code_B"]] if who == "both" else [r[f"code_{who}"]]
    return all(c in ("ACCURATE", "OVERREACH") for c in codes)


def share_lines(rows, label):
    n = len(rows)
    sub_both = [r for r in rows if substantive(r, "both")]
    out = [f"| {label} | {n} | "
           f"{fmt_share(sum(r['strict_over'] for r in rows), n)} | "
           f"{fmt_share(sum(r['lenient_over'] for r in rows), n)} | "
           f"{fmt_share(sum(r['code_A'] == 'OVERREACH' for r in rows), n)} | "
           f"{fmt_share(sum(r['code_B'] == 'OVERREACH' for r in rows), n)} | "
           f"{fmt_share(sum(r['strict_over'] for r in sub_both), len(sub_both))} |"]
    return out


def report(rows):
    a = [r["code_A"] for r in rows]
    b = [r["code_B"] for r in rows]
    k, po = cohen_kappa(a, b)
    lines = ["# Audit 04 results (generated by src/audit04/analyze.py)", "",
             f"Units: {len(rows)}. Cohen's kappa (4 codes): {k:.3f}; "
             f"raw agreement {po:.1%}.", ""]
    for t in sorted({r["target"] for r in rows}):
        sub = [r for r in rows if r["target"] == t]
        kt, pt = cohen_kappa([r["code_A"] for r in sub], [r["code_B"] for r in sub])
        lines.append(f"- {t}: kappa {kt:.3f}, raw agreement {pt:.1%}, n {len(sub)}")
    lines += ["", "Code counts (A / B): " + ", ".join(
        f"{c} {Counter(a)[c]}/{Counter(b)[c]}" for c in CODES), "",
        "Confusion (rows A, columns B):", "",
        "| A vs B | " + " | ".join(CODES) + " |",
        "|---|" + "---|" * len(CODES)]
    for ca in CODES:
        lines.append(f"| {ca} | " + " | ".join(
            str(sum(r["code_A"] == ca and r["code_B"] == cb for r in rows))
            for cb in CODES) + " |")
    head = ["", "Shares with Wilson 95% intervals. Strict = both coders OVERREACH; "
            "lenient = either coder. Last column: strict OVERREACH among units both "
            "coders coded ACCURATE or OVERREACH.", "",
            "| Group | n | Strict | Lenient | Coder A | Coder B | Strict, substantive |",
            "|---|---|---|---|---|---|---|"]
    lines += head
    for t in sorted({r["target"] for r in rows}):
        sub = [r for r in rows if r["target"] == t]
        lines += share_lines(sub, t)
        for bk in sorted({r["bucket"] for r in sub}):
            lines += share_lines([r for r in sub if r["bucket"] == bk], f"{t} {bk}")
        lines += share_lines([r for r in sub if not r["multi_any"]],
                             f"{t} single-cite only")
        lines += share_lines([r for r in sub if not r["hedged_any"]],
                             f"{t} unhedged only")
    lines += share_lines(rows, "Both targets")
    lines += ["", "Overreach subtypes among strict OVERREACH units "
              "(a unit can carry several):", ""]
    for t in sorted({r["target"] for r in rows}):
        st = [r for r in rows if r["target"] == t and r["strict_over"]]
        c = Counter(x for r in st for x in r["subtypes_agreed"].split(";") if x)
        lines.append(f"- {t} (n {len(st)}): " + ", ".join(
            f"{k} {v}" for k, v in c.most_common()))
    return "\n".join(lines) + "\n"


def main():
    rows = merge()
    with open(DATA / "merged.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    text = report(rows)
    (DATA / "results.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
